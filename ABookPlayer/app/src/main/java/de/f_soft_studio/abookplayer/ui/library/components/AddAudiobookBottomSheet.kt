/**
 * AddAudiobookBottomSheet: Bietet alle Optionen zum Importieren und Hinzufügen neuer Hörbücher.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun AddAudiobookBottomSheet(
    onImportFolder: () -> Unit,
    onImportFile: () -> Unit,
    onScanDefaultFolder: () -> Unit,
    onDismiss: () -> Unit,
    sheetState: SheetState = rememberModalBottomSheetState()
) {
    ModalBottomSheet(
        onDismissRequest = onDismiss,
        sheetState = sheetState,
        dragHandle = null
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .navigationBarsPadding()
                .padding(20.dp),
            verticalArrangement = Arrangement.spacedBy(14.dp)
        ) {
            Text(
                text = "Hörbücher hinzufügen",
                style = MaterialTheme.typography.titleLarge,
                fontWeight = FontWeight.Bold,
                color = MaterialTheme.colorScheme.onSurface
            )
            Text(
                text = "Wähle eine Methode, um neue Hörbücher in deine Bibliothek aufzunehmen:",
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onSurfaceVariant
            )

            Spacer(modifier = Modifier.height(2.dp))

            ImportOptionCard(
                icon = Icons.Default.FolderOpen,
                title = "Ordner importieren (SAF)",
                description = "Wähle einen ganzen Ordner mit Hörbuchdateien oder CD-Unterordnern aus.",
                onClick = {
                    onDismiss()
                    onImportFolder()
                }
            )

            ImportOptionCard(
                icon = Icons.Default.AudioFile,
                title = "Datei importieren",
                description = "Importiere einzelne .abook-, .zip-, .m4b- oder Audio-Dateien.",
                onClick = {
                    onDismiss()
                    onImportFile()
                }
            )

            ImportOptionCard(
                icon = Icons.Default.Refresh,
                title = "Standardordner scannen",
                description = "Durchsucht den Standardordner /ABook/ auf deinem Gerät nach neuen Titeln.",
                onClick = {
                    onDismiss()
                    onScanDefaultFolder()
                }
            )
        }
    }
}

@Composable
private fun ImportOptionCard(
    icon: ImageVector,
    title: String,
    description: String,
    onClick: () -> Unit,
    modifier: Modifier = Modifier
) {
    Card(
        modifier = modifier
            .fillMaxWidth()
            .clickable { onClick() },
        shape = RoundedCornerShape(14.dp),
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.7f))
    ) {
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(16.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Surface(
                shape = RoundedCornerShape(10.dp),
                color = MaterialTheme.colorScheme.primaryContainer,
                modifier = Modifier.size(48.dp)
            ) {
                Box(contentAlignment = Alignment.Center) {
                    Icon(
                        imageVector = icon,
                        contentDescription = null,
                        tint = MaterialTheme.colorScheme.primary,
                        modifier = Modifier.size(26.dp)
                    )
                }
            }

            Spacer(modifier = Modifier.width(16.dp))

            Column(modifier = Modifier.weight(1f)) {
                Text(
                    text = title,
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.Bold,
                    color = MaterialTheme.colorScheme.onSurface
                )
                Spacer(modifier = Modifier.height(2.dp))
                Text(
                    text = description,
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
            }
        }
    }
}
